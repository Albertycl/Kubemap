// Package install renders the install manifest: the namespaces, RBAC and
// workloads of the Kubemap server (Deployment kubemap in kubemap-system) and
// the node agents (DaemonSet in kubemap-node). `kubemap-agent bundle`
// prints it; deploy/kubemap.yaml is the checked-in copy.
//
// The manifest is generated, not written by hand, so that:
//   - the server's ClusterRole lists exactly the resources its cache watches
//     (cache.Resources), with get, list and watch only (A4, KM-47);
//   - the security settings (A4, A7, KM-48, KM-63) are checked by tests.
package install

import (
	"bytes"
	"fmt"
	"sort"

	appsv1 "k8s.io/api/apps/v1"
	corev1 "k8s.io/api/core/v1"
	rbacv1 "k8s.io/api/rbac/v1"
	"k8s.io/apimachinery/pkg/api/resource"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"k8s.io/apimachinery/pkg/runtime"
	"k8s.io/apimachinery/pkg/util/intstr"
	"sigs.k8s.io/yaml"

	"kubemap/agent/cluster/cache"
	"kubemap/agent/node/identity"
	"kubemap/pkg/protocol"
)

// Names used across the manifest.
const (
	SystemNamespace = "kubemap-system"
	NodeNamespace   = protocol.NodeAgentNamespace // kubemap-node
	// ServerName is the Deployment, Service, ServiceAccount and PVC name.
	ServerName = "kubemap"
	NodeAgent  = protocol.NodeAgentServiceAccount // kubemap-node-agent
	// DataClaim is the PVC that holds the SQLite database.
	DataClaim = "kubemap-data"
	// ServerPort is the plain-HTTP port; Traefik terminates TLS in front.
	ServerPort = 8080
	// LocalClusterID is the one cluster the server runs in. Node agents
	// use it as their cluster ID.
	LocalClusterID = "local"

	// ServerUID is the distroless "nonroot" user (A4, KM-48).
	ServerUID = 65532
	// NodeAgentUID is a user no other workload uses: with hostPID, a process
	// can read /proc/<pid>/environ of processes with the same UID, so the
	// node agent must not share 65532 with the server or with the many
	// images that default to it (review of KM-59, N1).
	NodeAgentUID = 65533
)

// NodeConnectURL is where node agents dial in: the cluster-internal Service.
const NodeConnectURL = "ws://" + ServerName + "." + SystemNamespace + ".svc:8080/v1/connect"

// Options change the manifest.
type Options struct {
	// Image holds the server and agent binaries, for example
	// "localhost/kubemap:v0.2.0" (imported into K3s) or a registry reference.
	Image string
	// PullPolicy defaults to IfNotPresent, which works for an imported image.
	PullPolicy corev1.PullPolicy
	// StorageClass of the data PVC; empty uses the cluster default.
	StorageClass string
}

// Bundle renders the manifest as YAML documents.
func Bundle(o Options) ([]byte, error) {
	if o.Image == "" {
		return nil, fmt.Errorf("install: image is required")
	}
	if o.PullPolicy == "" {
		o.PullPolicy = corev1.PullIfNotPresent
	}
	objs := []runtime.Object{
		namespace(SystemNamespace, "restricted", ""),
		namespace(NodeNamespace, "privileged", "The node agent needs hostPID and read-only host mounts (A7)."),
		serviceAccount(SystemNamespace, ServerName, true),
		readOnlyRole(),
		clusterBinding(ServerName+"-readonly", ServerName+"-readonly"),
		tokenReviewRole(),
		clusterBinding(ServerName+"-tokenreview", ServerName+"-tokenreview"),
		dataClaim(o),
		serverDeployment(o),
		serverService(),
		serviceAccount(NodeNamespace, NodeAgent, false),
		nodeAgentDaemonSet(o),
	}
	var out bytes.Buffer
	out.WriteString("# Kubemap install manifest (generated by `kubemap-agent bundle`; do not edit).\n")
	fmt.Fprintf(&out, "# Image %s.\n", o.Image)
	out.WriteString("# Read-only by design: the server's ClusterRole has get, list and watch only.\n")
	for _, obj := range objs {
		b, err := yaml.Marshal(obj)
		if err != nil {
			return nil, err
		}
		out.WriteString("---\n")
		out.Write(b)
	}
	return out.Bytes(), nil
}

func namespace(name, level, note string) *corev1.Namespace {
	ns := &corev1.Namespace{
		TypeMeta: metav1.TypeMeta{APIVersion: "v1", Kind: "Namespace"},
		ObjectMeta: metav1.ObjectMeta{Name: name, Labels: map[string]string{
			"app.kubernetes.io/managed-by":       "kubemap",
			"pod-security.kubernetes.io/enforce": level,
		}},
	}
	if note != "" {
		ns.Annotations = map[string]string{"kubemap.io/note": note}
	}
	return ns
}

func meta(ns, name string) metav1.ObjectMeta {
	return metav1.ObjectMeta{Namespace: ns, Name: name, Labels: map[string]string{
		"app.kubernetes.io/name": name, "app.kubernetes.io/part-of": "kubemap", "app.kubernetes.io/managed-by": "kubemap",
	}}
}

func serviceAccount(ns, name string, automount bool) *corev1.ServiceAccount {
	return &corev1.ServiceAccount{
		TypeMeta:                     metav1.TypeMeta{APIVersion: "v1", Kind: "ServiceAccount"},
		ObjectMeta:                   meta(ns, name),
		AutomountServiceAccountToken: &automount,
	}
}

var readVerbs = []string{"get", "list", "watch"}

// metricsVerbs are for pods.metrics.k8s.io.
var metricsVerbs = []string{"get", "list"}

// readOnlyRole lists every resource the cache watches, one rule per API
// group, plus pods/log (log view), as A4 approved. There is no nodes/stats
// and no nodes/proxy: the cluster agent makes no kubelet calls, so its
// cluster-wide read token is never sent to a node (review KM-60, approved
// 2026-09-28). Secrets are never in it: RBAC has no "all but" rule, which is
// why every resource is named.
func readOnlyRole() *rbacv1.ClusterRole {
	byGroup := map[string][]string{}
	for _, r := range cache.Resources() {
		byGroup[r.GVR.Group] = append(byGroup[r.GVR.Group], r.GVR.Resource)
	}
	byGroup[""] = append(byGroup[""], "pods/log")
	groups := make([]string, 0, len(byGroup))
	for g := range byGroup {
		groups = append(groups, g)
	}
	sort.Strings(groups)
	cr := &rbacv1.ClusterRole{
		TypeMeta:   metav1.TypeMeta{APIVersion: "rbac.authorization.k8s.io/v1", Kind: "ClusterRole"},
		ObjectMeta: meta("", ServerName+"-readonly"),
	}
	for _, g := range groups {
		res := uniq(byGroup[g])
		cr.Rules = append(cr.Rules, rbacv1.PolicyRule{APIGroups: []string{g}, Resources: res, Verbs: readVerbs})
	}
	// Per-pod usage (KM-28, KM-56) from metrics-server: get and list only,
	// the metrics API has no watch (approved 2026-09-28).
	cr.Rules = append(cr.Rules, rbacv1.PolicyRule{APIGroups: []string{"metrics.k8s.io"}, Resources: []string{"pods"}, Verbs: metricsVerbs})
	return cr
}

func uniq(s []string) []string {
	sort.Strings(s)
	out := s[:0]
	for i, v := range s {
		if i == 0 || v != s[i-1] {
			out = append(out, v)
		}
	}
	return out
}

func clusterBinding(name, role string) *rbacv1.ClusterRoleBinding {
	return &rbacv1.ClusterRoleBinding{
		TypeMeta:   metav1.TypeMeta{APIVersion: "rbac.authorization.k8s.io/v1", Kind: "ClusterRoleBinding"},
		ObjectMeta: meta("", name),
		RoleRef:    rbacv1.RoleRef{APIGroup: "rbac.authorization.k8s.io", Kind: "ClusterRole", Name: role},
		Subjects:   []rbacv1.Subject{{Kind: "ServiceAccount", Name: ServerName, Namespace: SystemNamespace}},
	}
}

// tokenReviewRole allows only creating TokenReviews, which stores nothing:
// the server checks each node agent's projected token with it.
// It is narrower than the built-in system:auth-delegator, which also allows
// SubjectAccessReviews.
func tokenReviewRole() *rbacv1.ClusterRole {
	return &rbacv1.ClusterRole{
		TypeMeta:   metav1.TypeMeta{APIVersion: "rbac.authorization.k8s.io/v1", Kind: "ClusterRole"},
		ObjectMeta: meta("", ServerName+"-tokenreview"),
		Rules: []rbacv1.PolicyRule{{
			APIGroups: []string{"authentication.k8s.io"}, Resources: []string{"tokenreviews"}, Verbs: []string{"create"},
		}},
	}
}

func ptr[T any](v T) *T { return &v }

// restricted is a container security context that passes Pod Security
// "restricted": non-root, no privilege escalation, no capabilities,
// read-only root filesystem, RuntimeDefault seccomp.
func restricted(uid int64) *corev1.SecurityContext {
	return &corev1.SecurityContext{
		RunAsNonRoot:             ptr(true),
		RunAsUser:                ptr(uid),
		RunAsGroup:               ptr(uid),
		AllowPrivilegeEscalation: ptr(false),
		Privileged:               ptr(false),
		ReadOnlyRootFilesystem:   ptr(true),
		Capabilities:             &corev1.Capabilities{Drop: []corev1.Capability{"ALL"}},
		SeccompProfile:           &corev1.SeccompProfile{Type: corev1.SeccompProfileTypeRuntimeDefault},
	}
}

func podSecurity(uid int64) *corev1.PodSecurityContext {
	return &corev1.PodSecurityContext{
		RunAsNonRoot:   ptr(true),
		RunAsUser:      ptr(uid),
		RunAsGroup:     ptr(uid),
		SeccompProfile: &corev1.SeccompProfile{Type: corev1.SeccompProfileTypeRuntimeDefault},
	}
}

// serverPodSecurity adds fsGroup so the data volume is writable by the
// server's group whatever the storage class does; OnRootMismatch skips the
// recursive chown once the volume already has the right owner.
func serverPodSecurity() *corev1.PodSecurityContext {
	sc := podSecurity(ServerUID)
	sc.FSGroup = ptr(int64(ServerUID))
	sc.FSGroupChangePolicy = ptr(corev1.FSGroupChangeOnRootMismatch)
	return sc
}

func quantity(s string) resource.Quantity { return resource.MustParse(s) }

func dataClaim(o Options) *corev1.PersistentVolumeClaim {
	pvc := &corev1.PersistentVolumeClaim{
		TypeMeta:   metav1.TypeMeta{APIVersion: "v1", Kind: "PersistentVolumeClaim"},
		ObjectMeta: meta(SystemNamespace, DataClaim),
		Spec: corev1.PersistentVolumeClaimSpec{
			AccessModes: []corev1.PersistentVolumeAccessMode{corev1.ReadWriteOnce},
			Resources: corev1.VolumeResourceRequirements{
				Requests: corev1.ResourceList{corev1.ResourceStorage: quantity("1Gi")}},
		},
	}
	if o.StorageClass != "" {
		pvc.Spec.StorageClassName = &o.StorageClass
	}
	return pvc
}

func serverService() *corev1.Service {
	return &corev1.Service{
		TypeMeta:   metav1.TypeMeta{APIVersion: "v1", Kind: "Service"},
		ObjectMeta: meta(SystemNamespace, ServerName),
		Spec: corev1.ServiceSpec{
			Selector: map[string]string{"app.kubernetes.io/name": ServerName},
			Ports:    []corev1.ServicePort{{Name: "http", Port: ServerPort, TargetPort: intstr.FromString("http")}},
		},
	}
}

// serverDeployment runs the server: the web UI, the API, the in-process
// cluster agent and the node agents' endpoint. One replica with Recreate: the
// SQLite database sits on a ReadWriteOnce volume, which also pins the pod to
// one node (a known limit).
func serverDeployment(o Options) *appsv1.Deployment {
	labels := map[string]string{"app.kubernetes.io/name": ServerName}
	probe := func(path string) *corev1.Probe {
		return &corev1.Probe{ProbeHandler: corev1.ProbeHandler{HTTPGet: &corev1.HTTPGetAction{Path: path, Port: intstr.FromString("http")}},
			PeriodSeconds: 10}
	}
	return &appsv1.Deployment{
		TypeMeta:   metav1.TypeMeta{APIVersion: "apps/v1", Kind: "Deployment"},
		ObjectMeta: meta(SystemNamespace, ServerName),
		Spec: appsv1.DeploymentSpec{
			Replicas: ptr(int32(1)),
			Selector: &metav1.LabelSelector{MatchLabels: labels},
			Strategy: appsv1.DeploymentStrategy{Type: appsv1.RecreateDeploymentStrategyType},
			Template: corev1.PodTemplateSpec{
				ObjectMeta: metav1.ObjectMeta{Labels: labels},
				Spec: corev1.PodSpec{
					ServiceAccountName: ServerName,
					SecurityContext:    serverPodSecurity(),
					Containers: []corev1.Container{{
						Name: "kubemap", Image: o.Image, ImagePullPolicy: o.PullPolicy,
						Command: []string{"/usr/local/bin/kubemap-portal"},
						Args:    []string{"run", "-listen", fmt.Sprintf(":%d", ServerPort), "-data-dir", "/data/kubemap"},
						Ports:   []corev1.ContainerPort{{Name: "http", ContainerPort: ServerPort}},
						Env: []corev1.EnvVar{{Name: "POD_NAMESPACE", ValueFrom: &corev1.EnvVarSource{
							FieldRef: &corev1.ObjectFieldSelector{FieldPath: "metadata.namespace"}}}},
						SecurityContext: restricted(ServerUID),
						// The server listens only after the cluster cache has synced
						// (up to 2 minutes), so liveness waits for the startup probe.
						StartupProbe: func() *corev1.Probe {
							p := probe("/healthz")
							p.PeriodSeconds, p.FailureThreshold = 5, 30
							return p
						}(),
						LivenessProbe:  probe("/healthz"),
						ReadinessProbe: probe("/healthz"),
						VolumeMounts:   []corev1.VolumeMount{{Name: "data", MountPath: "/data"}, {Name: "tmp", MountPath: "/tmp"}},
						Resources: corev1.ResourceRequirements{
							Requests: corev1.ResourceList{corev1.ResourceCPU: quantity("100m"), corev1.ResourceMemory: quantity("128Mi")},
							Limits:   corev1.ResourceList{corev1.ResourceMemory: quantity("384Mi")},
						},
					}},
					Volumes: []corev1.Volume{
						{Name: "data", VolumeSource: corev1.VolumeSource{PersistentVolumeClaim: &corev1.PersistentVolumeClaimVolumeSource{ClaimName: DataClaim}}},
						{Name: "tmp", VolumeSource: corev1.VolumeSource{EmptyDir: &corev1.EmptyDirVolumeSource{SizeLimit: ptr(quantity("64Mi"))}}},
					},
				},
			},
		},
	}
}

// nodeAgentDaemonSet runs one node agent per node (A7, KM-63): host PID
// view and recursively read-only host mounts for /proc, /sys and /, but no privileges,
// no capabilities, no Kubernetes API token. Its namespace allows the
// "privileged" Pod Security level only because host PID and hostPath need
// it. Its identity is a projected token bound to the pod and node (KM-68).
func nodeAgentDaemonSet(o Options) *appsv1.DaemonSet {
	labels := map[string]string{"app.kubernetes.io/name": NodeAgent}
	hostMount := func(name, host, at string) (corev1.Volume, corev1.VolumeMount) {
		return corev1.Volume{Name: name, VolumeSource: corev1.VolumeSource{HostPath: &corev1.HostPathVolumeSource{
				Path: host, Type: ptr(corev1.HostPathDirectory)}}},
			// Read-only all the way down (review-km-44 L5): without it, host
			// submounts such as /dev/shm, /run/lock or a tmpfs /tmp stay
			// writable through the / mount. Recursive read-only needs mount
			// propagation None, so a disk mounted on the host after the node
			// agent started is seen after its next restart (it was seen at
			// once with HostToContainer, review of KM-27 N3). IfPossible
			// falls back to a plain read-only mount on a runtime without
			// support (the API needs Kubernetes 1.30 or newer).
			corev1.VolumeMount{Name: name, MountPath: at, ReadOnly: true,
				// Read-only all the way down (review-km-44 L5): a plain
				// read-only hostPath leaves submounts such as /dev/shm,
				// /run/lock or other pods' volumes writable. Recursive
				// read-only needs mount propagation None, so a disk mounted
				// on the host after the pod started is not seen until the
				// pod restarts; the collector notices that instead of
				// measuring the wrong filesystem (agent/node/collect, fs.go).
				// IfPossible falls back to a plain read-only mount on a
				// runtime without support.
				RecursiveReadOnly: ptr(corev1.RecursiveReadOnlyIfPossible)}
	}
	var vols []corev1.Volume
	var mounts []corev1.VolumeMount
	for _, m := range [][3]string{{"host-root", "/", "/host"}, {"host-proc", "/proc", "/host/proc"}, {"host-sys", "/sys", "/host/sys"}} {
		v, vm := hostMount(m[0], m[1], m[2])
		vols, mounts = append(vols, v), append(mounts, vm)
	}
	vols = append(vols, corev1.Volume{Name: "kubemap-identity", VolumeSource: corev1.VolumeSource{Projected: &corev1.ProjectedVolumeSource{
		Sources: []corev1.VolumeProjection{{ServiceAccountToken: &corev1.ServiceAccountTokenProjection{
			Path: "token", Audience: protocol.NodeTokenAudience, ExpirationSeconds: ptr(int64(3600))}}},
	}}})
	mounts = append(mounts, corev1.VolumeMount{Name: "kubemap-identity", MountPath: "/var/run/secrets/kubemap", ReadOnly: true})
	return &appsv1.DaemonSet{
		TypeMeta:   metav1.TypeMeta{APIVersion: "apps/v1", Kind: "DaemonSet"},
		ObjectMeta: meta(NodeNamespace, NodeAgent),
		Spec: appsv1.DaemonSetSpec{
			Selector: &metav1.LabelSelector{MatchLabels: labels},
			Template: corev1.PodTemplateSpec{
				ObjectMeta: metav1.ObjectMeta{Labels: labels},
				Spec: corev1.PodSpec{
					ServiceAccountName:           NodeAgent,
					AutomountServiceAccountToken: ptr(false), // no Kubernetes API access at all
					HostPID:                      true,
					SecurityContext:              podSecurity(NodeAgentUID),
					// Every node, control plane included.
					Tolerations: []corev1.Toleration{{Operator: corev1.TolerationOpExists}},
					Containers: []corev1.Container{{
						Name: "node-agent", Image: o.Image, ImagePullPolicy: o.PullPolicy,
						Args: []string{"node", "--token", identity.DefaultTokenPath},
						Env: []corev1.EnvVar{
							{Name: "NODE_NAME", ValueFrom: &corev1.EnvVarSource{FieldRef: &corev1.ObjectFieldSelector{FieldPath: "spec.nodeName"}}},
							{Name: "CLUSTER_ID", Value: LocalClusterID},
							{Name: "PORTAL_URL", Value: NodeConnectURL},
						},
						SecurityContext: restricted(NodeAgentUID),
						VolumeMounts:    mounts,
						// The node budget (ARCHITECTURE): 64 MiB, 50m.
						Resources: corev1.ResourceRequirements{
							Requests: corev1.ResourceList{corev1.ResourceCPU: quantity("50m"), corev1.ResourceMemory: quantity("32Mi")},
							Limits:   corev1.ResourceList{corev1.ResourceMemory: quantity("64Mi")},
						},
					}},
					Volumes: vols,
				},
			},
		},
	}
}
